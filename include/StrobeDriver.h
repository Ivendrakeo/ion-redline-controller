/* pulsetrain driver for strobe kit */
#ifndef _STROBEDRIVER_H
#define _STROBEDRIVER_H

#include <stdint.h>


// State of all 4 strobe LEDs

typedef union {
    // address all strobes
    uint8_t allStrobes;

    // address individual strobes
    struct {
        uint8_t unused:4;
        uint8_t driverHeadlight:1;
        uint8_t driverFoglight:1;
        uint8_t passengerHeadlight:1;
        uint8_t passengerFoglight:1;
    }strobe;

}StrobeState;


/*
Pulse train protocol (output on STROBE_PULSE_GPIO_NUM, see HwDefs.h)

Each strobe_set() call sends one frame of STROBE_PULSE_COUNT high-going pulses at
STROBE_PULSE_FREQ_HZ, then holds the line low for STROBE_FRAME_GAP_US.
Each pulse encodes one bit: STROBE_DUTY_ON_PCT high time = on, STROBE_DUTY_OFF_PCT = off.

Bits go out LSB first, so pulse N carries bit (N-1) of StrobeState.allStrobes:
    pulses 1-4 : unused bits (always forced to "off")
    pulse 5    : driverHeadlight
    pulse 6    : driverFoglight
    pulse 7    : passengerHeadlight
    pulse 8    : passengerFoglight

Generated by an RMT TX channel, so pulse timing is hardware-accurate.
*/

#define STROBE_PULSE_COUNT          (8)
#define STROBE_PULSE_FREQ_HZ        (2000)      // 2 kHz -> 500 us period
#define STROBE_DUTY_ON_PCT          (70)        // duty cycle of an "on" pulse, percent
#define STROBE_DUTY_OFF_PCT         (30)        // duty cycle of an "off" pulse, percent
#define STROBE_FRAME_GAP_US         (2000)      // idle-low time after each frame
#define STROBE_RMT_RESOLUTION_HZ    (1000000)   // 1 MHz, 1 tick = 1 us

// Bits of allStrobes that are actually wired to strobes (pulses 5-8)
#define STROBE_USED_MASK            (0xF0)

// Create the RMT channel and encoder. Call once before strobe_set().
void init_strobe(void);

// Send one pulse-train frame for the given state.
// Waits for any previous frame (including its gap) to finish, then queues
// the new frame and returns without waiting for it. Not thread-safe.
void strobe_set(StrobeState strobeState);

// Block until the last queued frame (including its gap) has finished.
void strobe_wait_done(void);

#endif // _STROBEDRIVER_H
